import type { Lang } from "../../i18n";

/**
 * بيانات المقال — في `meta.ts` بجانب نصّه، لا داخله.
 *
 * لو كانت داخل ملف MDX لاضطُرّ الفهرس إلى استيراد كل مقال استيرادًا
 * ساكنًا ليقرأ عنوانه، فيدخل نصّ كل المقالات في الحزمة الأولى —
 * أي أن قارئ الصفحة الرئيسية يُحمّل المدوّنة كاملةً. الآن يُحمَّل
 * الوصف وحده، والنصّ عند فتحه.
 *
 * وهي ثنائية اللغة كبقية محتوى الموقع: اللغة الغائبة هنا تعني أن
 * المقال غير موجود بها، فلا يُولَّد له رابط ولا `hreflang`.
 */
export type PostText = {
  title: string;
  description: string;
};

export type PostEntry = {
  /** ISO: 2026-01-15 */
  date: string;
  updated?: string;
  tags: string[];
  /** صورة الغلاف — تدخل وسوم المشاركة وخريطة الموقع */
  cover?: string;
  /** الخدمة التي يقود إليها المقال — منها يُبنى نداء الإجراء */
  service?: string;
  draft?: boolean;
} & Partial<Record<Lang, PostText>>;
