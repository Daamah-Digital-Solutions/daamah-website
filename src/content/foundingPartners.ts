export function seatsLeft(n: number): string {
  if (n <= 0) return "اكتملت المقاعد";
  if (n === 1) return "باقي مقعد واحد";
  if (n === 2) return "باقي مقعدين";
  if (n <= 10) return `باقي ${n} مقاعد`;
  return `باقي ${n} مقعد`;
}

