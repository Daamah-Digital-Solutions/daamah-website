/**
 * واتساب برسالة جاهزة، وسطر المصدر إن وُجد: «من صفحة العرض» تعرّفنا
 * أن العميل جاء من الإعلان، والحملة تعرّفنا أيّها.
 * الرقم السعودي حين يُضاف إلى `brand.phones`، وإلا الدولي.
 */
export function launchWa(message: string, withSource = true): string {
  const number = phoneFor("sa").raw.replace(/\D/g, "");
  /* بلا مصدر وقت الرسم: ما يولَّد عند البناء يجب أن يطابق ما يرسمه
     المتصفح، والمصدر يُضاف لحظة الضغط */
  const src = withSource && typeof window !== "undefined" ? sourceLine() : "";
  const text = src ? `${message}\n(المصدر: ${src})` : message;
  return `https://wa.me/${number}?text=${encodeURIComponent(text)}`;
}

